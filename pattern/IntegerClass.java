package pattern;

public class IntegerClass {

	public static void main(String[] args) {
		
		// valueOf Integer Method
        String a = "2434";
        Integer b =Integer.valueOf(a);
        System.out.println(b);
        
        // intValue Integer Method
        Integer org = 6;
        int c = org.intValue();
        System.out.println(c);
        
        // toString Integer Method
        Integer z = 1245;
        String f = z.toString();
        System.out.println(f);

	}

}
