package pattern;

// Number increase from left to right side like triangle

public class Pattern_3 {

	public static void main(String[] args) {
		
		for(int i=1;i<=5;i++)
		{
		    for(int j=1;j<=i;j++)
		    {
		        System.out.print(j+" ");
		    }
		    System.out.println();
		}

	}

}
